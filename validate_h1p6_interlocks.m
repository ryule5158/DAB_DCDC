function results = validate_h1p6_interlocks()
%VALIDATE_H1P6_INTERLOCKS Verify safe entry and lockout behavior.
rootDir = fileparts(mfilename('fullpath'));
notesDir = fullfile(rootDir, 'DAB_RA8P1_PCB_Notes');
mdl = "DAB_RA8P1_Final_Physical_MOSFET";
if ~bdIsLoaded(mdl)
    open_system(fullfile(notesDir, mdl + ".slx"));
end
cases = struct( ...
    'Name', {"SAFE_DEFAULT", "NORMAL_PRECHARGED", "FAULT_LOCKOUT", ...
        "DOMAIN_LOCKOUT", "COLD_START_LIMITED"}, ...
    'Vin', {24, 24, 24, 32, 24}, 'RunReq', {0, 1, 1, 1, 1}, ...
    'FaultN', {1, 1, 0, 1, 1}, 'Precharge', {0, 48, 48, 48, 0}, ...
    'ExpectSwitching', {false, true, false, false, true}, ...
    'ExpectStartupLimit', {false, false, false, false, true});
rows = repmat(struct('Case', "", 'MaxAbsPhase_us', NaN, ...
    'MaxActualVgs_V', NaN, 'SwitchingObserved', false, ...
    'IpriPeak_A', NaN, 'IsecPeak_A', NaN, ...
    'VoutFinal_V', NaN, 'Pass', false), numel(cases), 1);
for k = 1:numel(cases)
    cfg = cases(k);
    in = Simulink.SimulationInput(mdl);
    in = in.setModelParameter('StopTime', '0.00035', ...
        'SimscapeLogType', 'all', ...
        'ReturnWorkspaceOutputs', 'on');
    in = in.setBlockParameter(Simulink.ID.getFullName(mdl + ":1"), ...
        'dc_voltage', text_value(cfg.Vin));
    in = in.setBlockParameter(Simulink.ID.getFullName(mdl + ":401"), ...
        'Value', text_value(cfg.RunReq));
    in = in.setBlockParameter(Simulink.ID.getFullName(mdl + ":402"), ...
        'Value', text_value(cfg.FaultN));
    for sid = [44 46 50 376]
        capPath = Simulink.ID.getFullName(mdl + ":" + sid);
        in = in.setBlockParameter(capPath, 'vc_specify', 'on');
        in = in.setBlockParameter(capPath, 'vc_priority', 'High');
        in = in.setBlockParameter(capPath, 'vc', text_value(cfg.Precharge));
        in = in.setBlockParameter(capPath, 'vc_unit', 'V');
    end
    out = sim(in);
    phase = out.DAB_RA8P1_Final_Physical_MOSFET_phase_us;
    maxAbsPhase = max(abs(phase.signals.values), [], 'all');
    maxActualVgs = max_gate_vgs(out.simlog);
    switching = maxActualVgs > 2;
    ipri = out.DAB_RA8P1_Final_Physical_MOSFET_ipri_hf;
    isec = out.DAB_RA8P1_Final_Physical_MOSFET_isec_hf;
    vout = out.DAB_RA8P1_Final_Physical_MOSFET_vout;
    ipriPeak = max(abs(ipri.signals.values), [], 'all');
    isecPeak = max(abs(isec.signals.values), [], 'all');
    startupLimitPass = ~cfg.ExpectStartupLimit || ...
        (ipriPeak <= 35 && isecPeak <= 20 && vout.signals.values(end) > 0);
    rows(k) = struct('Case', cfg.Name, 'MaxAbsPhase_us', maxAbsPhase, ...
        'MaxActualVgs_V', maxActualVgs, ...
        'SwitchingObserved', switching, 'IpriPeak_A', ipriPeak, ...
        'IsecPeak_A', isecPeak, 'VoutFinal_V', vout.signals.values(end), ...
        'Pass', switching == cfg.ExpectSwitching && startupLimitPass);
end
results = struct2table(rows);
disp(results);
assert(all(results.Pass), 'H1.6 interlock validation failed.');
writetable(results, fullfile(notesDir, 'final_physical_models_screenshots', ...
    'DAB_RA8P1_H1p6_Interlock_Check.csv'));
fprintf('PASS: H1.6 interlock behavior.\n');
end

function maxVgs = max_gate_vgs(simlog)
p = simlog.PRI_Full_Bridge_RealDrivers;
s = simlog.SEC_Full_Bridge_RealDrivers;
nodes = {p.Leg_A_RealSwitchingCell.Q1_PRI_A_HS; ...
    p.Leg_A_RealSwitchingCell.Q2_PRI_A_LS; ...
    p.Leg_B_RealSwitchingCell.Q3_PRI_B_HS; ...
    p.Leg_B_RealSwitchingCell.Q4_PRI_B_LS; ...
    s.Leg_A_RealSwitchingCell.Q5_SEC_A_HS; ...
    s.Leg_A_RealSwitchingCell.Q6_SEC_A_LS; ...
    s.Leg_B_RealSwitchingCell.Q7_SEC_B_HS; ...
    s.Leg_B_RealSwitchingCell.Q8_SEC_B_LS};
maxVgs = -inf;
for q = 1:numel(nodes)
    maxVgs = max(maxVgs, ...
        max(nodes{q}.voltage_gs.series.values, [], 'all'));
end
end

function value = text_value(value)
value = sprintf('%.12g', value);
end
