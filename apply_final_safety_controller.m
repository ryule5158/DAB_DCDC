function apply_final_safety_controller()
%APPLY_FINAL_SAFETY_CONTROLLER Install fail-safe startup and NORMAL_SPS control.
%   The saved model defaults to no switching. Cold start uses alternating
%   primary three-level pulses with measured IPRI/ISEC limits. NORMAL_SPS
%   requires RUN_REQ, RAW_FAULT_N, 20 valid samples, and the voltage domain.

rootDir = fileparts(mfilename('fullpath'));
modelFile = fullfile(rootDir, 'DAB_RA8P1_PCB_Notes', ...
    'DAB_RA8P1_Final_Physical_MOSFET.slx');
mdl = 'DAB_RA8P1_Final_Physical_MOSFET';

if ~bdIsLoaded(mdl)
    open_system(modelFile);
end

rt = sfroot;
chart = rt.find('-isa', 'Stateflow.EMChart', ...
    'Path', [mdl '/RA8P1_Realtime_Voltage_PI']);
assert(~isempty(chart), 'RA8P1 controller MATLAB Function was not found.');
chart.Script = controller_script();
chart.ChartUpdate = 'DISCRETE';
chart.SampleTime = '1e-7';
save_system(mdl, modelFile);
fprintf('UPDATED_CONTROLLER=%s\n', modelFile);
end

function script = controller_script()
lines = [
"function [g1,g2,g3,g4,g5,g6,g7,g8,PhaseUs] = f(t,Vout,VrefCmd,Vin,Iout,Ipri,Isec,RunReq,RawFaultN)"
"%#codegen"
"% Cold start: alternating primary three-level pulses, secondary gates off."
"% NORMAL_SPS starts only after 20 consecutive voltage-domain samples."
"persistent trim prevErr lastTick vFilt vinFilt iFilt permitCount normalEnabled startupEnabled startupCycle startupPulseAllowed startupPolarity normalRamp iPriPeakHold iSecPeakHold startupPulseCmd startupIpriCyclePeak startupIsecCyclePeak"
"if isempty(trim)"
"    trim = 0;"
"    prevErr = 0;"
"    lastTick = -1;"
"    vFilt = 0;"
"    vinFilt = 24;"
"    iFilt = 0;"
"    permitCount = uint16(0);"
"    normalEnabled = false;"
"    startupEnabled = false;"
"    startupCycle = -1;"
"    startupPulseAllowed = false;"
"    startupPolarity = false;"
"    normalRamp = 0;"
"    iPriPeakHold = 0;"
"    iSecPeakHold = 0;"
"    startupPulseCmd = 100e-9;"
"    startupIpriCyclePeak = 0;"
"    startupIsecCyclePeak = 0;"
"end"
"fs = 300e3;"
"T = 1/fs;"
"deadTime = 120e-9;"
"TsCtrl = 10e-6;"
"tick = floor(t/TsCtrl);"
"Vref = min(max(VrefCmd,36),48);"
"rawVoltageOk = Vin >= 18 && Vin <= 28 && Vout >= -0.5 && Vout < 50;"
"faultOk = RunReq > 0.5 && RawFaultN > 0.5 && rawVoltageOk;"
"iPriPeakHold = max(iPriPeakHold,abs(Ipri));"
"iSecPeakHold = max(iSecPeakHold,abs(Isec));"
"startupIpriCyclePeak = max(startupIpriCyclePeak,abs(Ipri));"
"startupIsecCyclePeak = max(startupIsecCyclePeak,abs(Isec));"
"if tick ~= lastTick"
"    if lastTick < 0"
"        vFilt = Vout;"
"        vinFilt = Vin;"
"        iFilt = abs(Iout);"
"    else"
"        vFilt = vFilt + 0.40*(Vout - vFilt);"
"        vinFilt = vinFilt + 0.10*(Vin - vinFilt);"
"        iFilt = iFilt + 0.22*(abs(Iout) - iFilt);"
"    end"
"    ratioMismatch = abs(Vout - 2*Vin);"
"    entryRatioOk = (Vout < 2*Vin && ratioMismatch <= 7.0) || ..."
"        (Vout >= 2*Vin && ratioMismatch <= 12.5);"
"    holdRatioOk = (Vout < 2*Vin && ratioMismatch < 10.0) || ..."
"        (Vout >= 2*Vin && ratioMismatch < 13.5);"
"    startupOk = faultOk && vinFilt >= 18 && vinFilt <= 28 && ..."
"        vFilt >= -0.5 && vFilt < 50;"
"    entryOk = faultOk && vinFilt >= 18 && vinFilt <= 28 && ..."
"        vFilt >= 36 && vFilt <= 48 && entryRatioOk;"
"    holdOk = faultOk && vinFilt >= 18 && vinFilt <= 28 && ..."
"        vFilt >= 36 && vFilt <= 48 && holdRatioOk;"
"    if normalEnabled"
"        if ~holdOk"
"            normalEnabled = false;"
"            startupEnabled = startupOk;"
"            startupPulseCmd = startup_pulse_width(Vout,Vin);"
"            startupCycle = -1;"
"            startupPolarity = false;"
"            permitCount = uint16(0);"
"            trim = 0;"
"            normalRamp = 0;"
"        end"
"    else"
"        if ~startupOk"
"            startupEnabled = false;"
"            permitCount = uint16(0);"
"        elseif entryOk"
"            startupEnabled = false;"
"            if permitCount < uint16(20)"
"                permitCount = permitCount + uint16(1);"
"            end"
"        else"
"            if ~startupEnabled"
"                startupPulseCmd = startup_pulse_width(Vout,Vin);"
"                startupCycle = -1;"
"                startupPolarity = false;"
"                startupIpriCyclePeak = 0;"
"                startupIsecCyclePeak = 0;"
"            end"
"            startupEnabled = true;"
"            permitCount = uint16(0);"
"        end"
"        if permitCount >= uint16(20)"
"            normalEnabled = true;"
"            startupEnabled = false;"
"            normalRamp = 0;"
"            trim = 0;"
"            prevErr = Vref - vFilt;"
"        end"
"    end"
"    if normalEnabled"
"        normalIpriLow = min(48,36 + 1.2*iFilt);"
"        normalIsecLow = min(24,18 + 0.6*iFilt);"
"        if iPriPeakHold < normalIpriLow && iSecPeakHold < normalIsecLow"
"            normalRamp = min(1,normalRamp + 0.005);"
"        elseif iPriPeakHold >= normalIpriLow + 4 || iSecPeakHold >= normalIsecLow + 2"
"            normalRamp = max(0,normalRamp - 0.05);"
"        end"
"        err = Vref - vFilt;"
"        dErr = err - prevErr;"
"        trim = 0.965*trim + 0.0102e-6*err + 0.0033e-6*dErr;"
"        trimLimit = 0.100e-6;"
"        if iFilt < 0.70"
"            trimLimit = 0.016e-6;"
"        end"
"        trim = min(max(trim, -trimLimit), trimLimit);"
"        prevErr = err;"
"    else"
"        trim = 0;"
"        normalRamp = 0;"
"    end"
"    iPriPeakHold = abs(Ipri);"
"    iSecPeakHold = abs(Isec);"
"    lastTick = tick;"
"end"
"if normalEnabled && faultOk"
"    phase = normalRamp*(base_phase(Vref, vinFilt, iFilt) + trim);"
"    phase = min(max(phase, -0.55e-6), 0.46e-6);"
"    [a,an] = halfbridge(t,T,deadTime);"
"    [b,bn] = halfbridge(t+T/2,T,deadTime);"
"    [c,cn] = halfbridge(t-phase,T,deadTime);"
"    [d,dn] = halfbridge(t-phase+T/2,T,deadTime);"
"    g1 = 10*a;  g2 = 10*an;"
"    g3 = 10*b;  g4 = 10*bn;"
"    g5 = 10*c;  g6 = 10*cn;"
"    g7 = 10*d;  g8 = 10*dn;"
"    PhaseUs = phase*1e6;"
"elseif startupEnabled && faultOk"
"    startupSlotPeriod = T/2;"
"    cycle = floor(t/startupSlotPeriod);"
"    if cycle ~= startupCycle"
"        if startupCycle >= 0"
"            adaptDeltaV = max(Vin - 0.5*Vout,2);"
"            pulseStepUp = 5e-9 + 15e-9*min(max((10-adaptDeltaV)/6,0),1);"
"            if startupIpriCyclePeak < 28 && startupIsecCyclePeak < 14"
"                startupPulseCmd = startupPulseCmd + pulseStepUp;"
"            elseif startupIpriCyclePeak > 31 || startupIsecCyclePeak > 16"
"                startupPulseCmd = startupPulseCmd - 40e-9;"
"            end"
"        end"
"        startupPulseCmd = max(startupPulseCmd,startup_pulse_width(Vout,Vin));"
"        startupPulseCmd = min(max(startupPulseCmd,100e-9),1.3e-6);"
"        startupDeltaV = max(Vin - 0.5*Vout,2);"
"        if startupDeltaV >= 12"
"            highDeltaCap = 26*0.1e-6/startupDeltaV + 35e-9;"
"            startupPulseCmd = min(startupPulseCmd,highDeltaCap);"
"        end"
"        if Vout < 15"
"            % 24A volt-second cap using 0.4uH secondary leakage / 4."
"            lowVoltageCap = 24*0.1e-6/startupDeltaV;"
"            lowVoltageCap = min(max(lowVoltageCap,100e-9),185e-9);"
"            startupPulseCmd = min(startupPulseCmd,lowVoltageCap);"
"        end"
"        startupPulseAllowed = abs(Ipri) < 3 && abs(Isec) < 3 && ..."
"            Vout < Vref - 0.05;"
"        if startupPulseAllowed"
"            startupPolarity = ~startupPolarity;"
"        end"
"        startupCycle = cycle;"
"        startupIpriCyclePeak = abs(Ipri);"
"        startupIsecCyclePeak = abs(Isec);"
"    end"
"    if abs(Ipri) >= 35 || abs(Isec) >= 20"
"        startupPulseAllowed = false;"
"    end"
"    if startupPulseAllowed"
"        [p1,p2,p3,p4] = startup_bridge(t,startupSlotPeriod,deadTime,startupPulseCmd,startupPolarity);"
"        g1 = 10*p1; g2 = 10*p2; g3 = 10*p3; g4 = 10*p4;"
"    else"
"        g1 = 0; g2 = 0; g3 = 0; g4 = 0;"
"    end"
"    g5 = 0; g6 = 0; g7 = 0; g8 = 0;"
"    PhaseUs = startupPulseCmd*1e6*double(g1 > 0 || g2 > 0 || g3 > 0 || g4 > 0);"
"else"
"    g1 = 0; g2 = 0; g3 = 0; g4 = 0;"
"    g5 = 0; g6 = 0; g7 = 0; g8 = 0;"
"    PhaseUs = 0;"
"end"
"end"
""
"function pulseWidth = startup_pulse_width(Vout,Vin)"
"% Use the 0.4uH secondary-referred minimum leakage (0.1uH primary)."
"deltaV = max(Vin - 0.5*Vout,2);"
"pulseWidth = 30*0.1e-6/deltaV;"
"delayComp = 100e-9*min(max((15-deltaV)/10,0),1);"
"pulseWidth = pulseWidth + delayComp;"
"pulseWidth = min(max(pulseWidth,100e-9),900e-9);"
"end"
""
"function [q1,q2,q3,q4] = startup_bridge(t,T,deadTime,pulseWidth,polarity)"
"x = mod(t,T);"
"active = double(x >= deadTime && x < deadTime + pulseWidth);"
"freewheel = double(x >= deadTime + pulseWidth + deadTime);"
"lowAfterBoundary = double(x >= deadTime);"
"if polarity"
"    q1 = active; q2 = freewheel; q3 = 0; q4 = lowAfterBoundary;"
"else"
"    q1 = 0; q2 = lowAfterBoundary; q3 = active; q4 = freewheel;"
"end"
"end"
""
"function phase = base_phase(Vref,Vin,Iout)"
"buckDelta = Vin - 0.5*Vref;"
"if buckDelta > 0.6"
"    light = max(0, 1.7 - Iout);"
"    lowBuckTrim = 0.0096*exp(-((buckDelta - 2.0)/2.0)^2) + 0.0040*exp(-((buckDelta - 4.0)/1.2)^2);"
"    lightBuckTrim = 0.0085*exp(-((Iout - 0.52)/0.22)^2)*min(max((buckDelta - 2.0)/4.0, 0), 1);"
"    midBuckGain = 0.012 + 0.012*min(max((buckDelta - 2.0)/4.0, 0), 1);"
"    midBuckLoadTrim = midBuckGain*exp(-((Iout - 1.22)/0.42)^2);"
"    lowBuckMidRelief = 0.0076*exp(-((Iout - 1.10)/0.30)^2)*exp(-((buckDelta - 2.0)/0.90)^2);"
"    highBuckLoad = max(Iout - 3.2, 0);"
"    highBuckReliefRaw = 0.0038*highBuckLoad^2 + 0.0050*max(Iout - 10.0, 0)^2 + 0.0340*max(Iout - 11.5, 0)^2;"
"    highBuckRelief = min(highBuckReliefRaw, 0.594);"
"    phaseUs = -0.229 - 0.0165*buckDelta - 0.0110*min(Iout,3.2) - 0.020*light - lowBuckTrim - lightBuckTrim - midBuckLoadTrim + lowBuckMidRelief + highBuckRelief;"
"else"
"    highBoostLoad = max(Iout - 3.0, 0);"
"    highBoostBackoff = 0.128*(1 - exp(-highBoostLoad/1.6)) + 0.02925*max(Iout - 7.0, 0);"
"    phaseUs = -0.028 + 0.112*min(Iout,2.3) + 0.038*max(Iout-1.4,0) - highBoostBackoff;"
"end"
"if buckDelta > 0.6"
"    phaseUs = phaseUs + 0.095*exp(-((Iout - 13.0)/3.0)^2)*exp(-((buckDelta - 6.0)/1.4)^2);"
"else"
"    phaseUs = phaseUs + 0.010*(1 - exp(-max(Iout - 7.0, 0)/2.0));"
"    phaseUs = phaseUs + 0.020*exp(-(buckDelta/0.75)^2)*exp(-((Iout - 2.1)/1.0)^2);"
"end"
"phase = min(max(phaseUs*1e-6, -0.55e-6), 0.46e-6);"
"end"
""
"function [hi,lo] = halfbridge(t,T,deadTime)"
"x = mod(t,T);"
"halfDead = deadTime/2;"
"hi = double(x >= halfDead && x < T/2 - halfDead);"
"lo = double(x >= T/2 + halfDead && x < T - halfDead);"
"end"
];
script = char(strjoin(lines, newline));
end
